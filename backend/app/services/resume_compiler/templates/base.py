from typing import Dict, Any, Optional

def get_base_preamble(
    font_size: str = "10.8pt",
    margins: str = "0.5in",
    spacing: str = "compact",
    font_package: str = "lmodern",
    section_rule_color: str = "black",
    custom_macros: Optional[str] = None
) -> str:
    """
    Generates an ATS-compliant, compile-safe LaTeX document preamble.
    Ensures glyphtounicode is active for perfect text extraction,
    standard itemize environments, and uniform headings without tables that break ATS parsers.
    """
    # Spacing adjustments
    if spacing == "tight":
        top_margin_adj = "-0.65in"
        bottom_adj = "1.25in"
        item_sep = "-3pt"
        sec_before = "-6pt"
        sec_after = "-7pt"
    elif spacing == "compact":
        top_margin_adj = "-0.55in"
        bottom_adj = "1.1in"
        item_sep = "-2pt"
        sec_before = "-4pt"
        sec_after = "-5pt"
    else: # normal
        top_margin_adj = "-0.45in"
        bottom_adj = "0.9in"
        item_sep = "-1pt"
        sec_before = "-2pt"
        sec_after = "-3pt"

    font_cmd = f"\\usepackage{{{font_package}}}" if font_package else ""

    macros = custom_macros or f"""
\\newcommand{{\\resumeItem}}[1]{{\\item\\small{{#1}}}}
\\newcommand{{\\resumeSubheading}}[4]{{
  \\vspace{{{item_sep}}}\\item
    \\begin{{tabular*}}{{0.97\\textwidth}}[t]{{l@{{\\extracolsep{{\\fill}}}}r}}
      \\textbf{{#1}} & #2 \\\\
      \\textit{{\\small#3}} & \\textit{{\\small #4}} \\\\
    \\end{{tabular*}}\\vspace{{{sec_after}}}
}}
\\newcommand{{\\resumeProjectHeading}}[2]{{
  \\vspace{{{item_sep}}}\\item
    \\begin{{tabular*}}{{0.97\\textwidth}}[t]{{l@{{\\extracolsep{{\\fill}}}}r}}
      #1 & #2 \\\\
    \\end{{tabular*}}\\vspace{{{sec_after}}}
}}
\\newcommand{{\\resumeSubHeadingListStart}}{{\\begin{{itemize}}[leftmargin=0.15in, label={{}}]}}
\\newcommand{{\\resumeSubHeadingListEnd}}{{\\end{{itemize}}}}
\\newcommand{{\\resumeItemListStart}}{{\\begin{{itemize}}[topsep=0pt, parsep=0pt, itemsep=1pt]}}
\\newcommand{{\\resumeItemListEnd}}{{\\end{{itemize}}\\vspace{{{sec_after}}}}}
"""

    preamble = f"""%-------------------------
% Modular ATS Resume
% Generated by Interview AutoApply
%-------------------------

\\documentclass[letterpaper,{font_size}]{{article}}

\\usepackage{{latexsym}}
\\usepackage[empty]{{fullpage}}
\\usepackage{{titlesec}}
\\usepackage[usenames,dvipsnames]{{color}}
\\usepackage{{enumitem}}
\\usepackage[hidelinks]{{hyperref}}
\\usepackage{{fancyhdr}}
\\usepackage[english]{{babel}}
\\usepackage{{tabularx}}
{font_cmd}
\\input{{glyphtounicode}}

\\pagestyle{{fancy}}
\\fancyhf{{}}
\\renewcommand{{\\headrulewidth}}{{0pt}}

\\addtolength{{\\oddsidemargin}}{{-0.5in}}
\\addtolength{{\\textwidth}}{{1.0in}}
\\addtolength{{\\topmargin}}{{{top_margin_adj}}}
\\addtolength{{\\textheight}}{{{bottom_adj}}}

\\raggedright
\\setlength{{\\tabcolsep}}{{0in}}
\\pdfgentounicode=1

\\titleformat{{\\section}}{{
  \\vspace{{{sec_before}}}\\scshape\\raggedright\\large
}}{{}}{{0em}}{{}}[\\titlerule \\vspace{{{sec_after}}}]

{macros}
"""
    return preamble.strip()
